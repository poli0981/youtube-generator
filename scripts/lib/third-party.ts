/** Production packages (bundled into the app) whose license is not allowed. */
export function disallowedProductionLicenses(): string[] {
  const lock = readJson<{
    packages: Record<string, { dev?: boolean; devOptional?: boolean; license?: unknown }>;
  }>(resolve(ROOT, "package-lock.json"));
  const bad: string[] = [];
  for (const [path, entry] of Object.entries(lock.packages)) {
    if (path === "" || entry.dev || entry.devOptional) continue;
    const license = typeof entry.license === "string" ? entry.license : "UNKNOWN";
    if (!licenseAllowed(license)) bad.push(`${path.replace(/^.*node_modules\//, "")} (${license})`);
  }
  return bad;
}

export function main(): void {
  const write = process.argv.includes("--write");
  const expected = renderNotices();
  if (write) {
    writeFileSync(NOTICES, expected);
    console.log("THIRD_PARTY_NOTICES.md regenerated.");
    return;
  }
  let failed = false;
  const bad = disallowedProductionLicenses();
  if (bad.length > 0) {
    failed = true;
    console.error(`✗ Bundled packages with licenses outside the allowlist:\n  ${bad.join("\n  ")}`);
  } else {
    console.log("✓ Every bundled package has an allowed license.");
  }
  const current = readFileSync(NOTICES, "utf8").replace(/\r\n/g, "\n");
  if (current !== expected) {
    failed = true;
    console.error("✗ THIRD_PARTY_NOTICES.md is stale — run `npm run generate:third-party`.");
  } else {
    console.log("✓ THIRD_PARTY_NOTICES.md matches package.json, the lockfile and Cargo.toml.");
  }
  if (failed) process.exit(1);
}
