/**
 * Third-party licensing, generated and enforced.
 *
 *   npm run generate:third-party   rewrite THIRD_PARTY_NOTICES.md
 *   npm run check:licenses          fail if it is stale, or if anything shipped
 *                                   to users carries a license not on the list
 *
 * THIRD_PARTY_NOTICES.md used to be hand-maintained and had drifted three
 * majors behind (React 18, Vite 7, Tailwind 3 …). It is now built from
 * package.json, the installed packages and Cargo.toml/Cargo.lock, so CI
 * catches the drift instead of a reader. The full license texts of every
 * package bundled into the web app are emitted separately by Vite
 * (`build.license`) to /licenses/third-party.md.
 */
import { readFileSync, writeFileSync } from "fs";
import { resolve } from "path";

const ROOT = resolve(import.meta.dirname, "../..");
const NOTICES = resolve(ROOT, "THIRD_PARTY_NOTICES.md");

/** Licenses acceptable for code that ships inside the app. */
const ALLOWED = new Set([
  "MIT",
  "ISC",
  "Apache-2.0",
  "BSD-2-Clause",
  "BSD-3-Clause",
  "0BSD",
  "CC0-1.0",
  "Unlicense",
  "BlueOak-1.0.0",
  "OFL-1.1",
  "Zlib",
  "MPL-2.0",
]);

/** SPDX expression → allowed? `OR` needs one side, `AND` needs both. */
export function licenseAllowed(expression: string): boolean {
  const expr = expression.trim().replace(/^\((.*)\)$/, "$1");
  if (/\sOR\s/i.test(expr)) return expr.split(/\s+OR\s+/i).some(licenseAllowed);
  if (/\sAND\s/i.test(expr)) return expr.split(/\s+AND\s+/i).every(licenseAllowed);
  return ALLOWED.has(expr);
}

interface PackageJson {
  version?: string;
  license?: string;
  homepage?: string;
  repository?: string | { url?: string };
  dependencies?: Record<string, string>;
  devDependencies?: Record<string, string>;
}

function readJson<T>(path: string): T {
  return JSON.parse(readFileSync(path, "utf8")) as T;
}

function projectUrl(pkg: PackageJson): string {
  const repo = typeof pkg.repository === "string" ? pkg.repository : pkg.repository?.url;
  const fromRepo = repo
    ?.replace(/^git\+/, "")
    .replace(/^git:\/\//, "https://")
    .replace(/^github:/, "https://github.com/")
    .replace(/\.git$/, "");
  if (fromRepo && /^https?:\/\//.test(fromRepo)) return fromRepo;
  if (fromRepo && /^[\w.-]+\/[\w.-]+$/.test(fromRepo)) return `https://github.com/${fromRepo}`;
  return pkg.homepage ?? "";
}

interface Row {
  name: string;
  version: string;
  license: string;
  url: string;
}

function npmRows(names: string[]): Row[] {
  return names.sort().map((name) => {
    const pkg = readJson<PackageJson>(resolve(ROOT, "node_modules", name, "package.json"));
    return {
      name,
      version: pkg.version ?? "?",
      license: pkg.license ?? "UNKNOWN",
      url: projectUrl(pkg),
    };
  });
}

function crateRows(): Row[] {
  const toml = readFileSync(resolve(ROOT, "src-tauri/Cargo.toml"), "utf8").replace(/\r\n/g, "\n");
  const lock = readFileSync(resolve(ROOT, "src-tauri/Cargo.lock"), "utf8").replace(/\r\n/g, "\n");
  const names = [...toml.matchAll(/^([a-z][a-z0-9_-]*)\s*=\s*(?:"|\{)/gm)]
    .map((m) => m[1] ?? "")
    .filter((n) => n.startsWith("tauri"));
  return [...new Set(names)].sort().map((name) => {
    const version =
      new RegExp(`\\[\\[package\\]\\]\\nname = "${name}"\\nversion = "([^"]+)"`).exec(lock)?.[1] ??
      "?";
    const url = name.startsWith("tauri-plugin")
      ? "https://github.com/tauri-apps/plugins-workspace"
      : "https://github.com/tauri-apps/tauri";
    return { name, version, license: "Apache-2.0 OR MIT", url };
  });
}

function table(rows: Row[], heading: string): string {
  const lines = rows.map(
    (r) => `| \`${r.name}\` | ${r.version} | ${r.license} | ${r.url ? `<${r.url}>` : "—"} |`,
  );
  return [
    `| ${heading} | Version | License | Project |`,
    "| --- | --- | --- | --- |",
    ...lines,
  ].join("\n");
}

